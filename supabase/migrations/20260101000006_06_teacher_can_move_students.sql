-- =============================================================================
--  Школьный дневник — шаг 06. Учитель может переводить ученика в другой класс
--
--  ЗАЧЕМ: экран «Отметки» даёт учителю выбор класса. Чтобы перевести ученика
--  (например, из 5А в 5Б) нужно обновить public.students.class_id. Политика
--  students_update_admin пускает в UPDATE только администратора, поэтому
--  добавляем отдельную политику для учителя: он может менять запись ученика
--  тех классов, которые сам ведёт (public.can_view_class), и перевести его
--  только в класс, который тоже ведёт (проверка with check по новому class_id).
--
--  ЧТО НЕ ДЕЛАЕТ: не удаляет отметки и посещаемость — ученик остаётся тем же
--  человеком (та же строка students.id), меняется только класс.
--
--  КАК ЗАПУСКАТЬ: Supabase → SQL Editor → New query → вставить файл целиком → Run.
--  Файл идемпотентный: повторный запуск безопасен.
--
--  ЕСЛИ ПЕРЕВОД ВСЁ РАВНО НЕ СРАБАТЫВАЕТ (сообщение про недостаток прав) —
--  проверьте, что учитель назначен на классы: supabase/promote_teacher.sql (Шаг 4).
-- =============================================================================

-- -----------------------------------------------------------------------------
--  1. Политика: учитель обновляет учеников своих классов
--     using      — срабатывает на текущую строку (класс, где ученик сейчас);
--     with check — на новую строку (класс, куда переводим).
-- -----------------------------------------------------------------------------
drop policy if exists students_update_teacher on public.students;

create policy students_update_teacher on public.students
  for update
  using (
    public.my_role() = 'teacher'
    and public.can_view_class(class_id)
  )
  with check (
    public.my_role() = 'teacher'
    and public.can_view_class(class_id)
  );

comment on policy students_update_teacher on public.students is
  'Учитель может менять ученика (в том числе переводить в другой класс), если ведёт его класс';

-- -----------------------------------------------------------------------------
--  2. Проверка (ничего не меняет): какие политики сейчас на public.students
-- -----------------------------------------------------------------------------
select policyname,
       cmd,
       coalesce(qual, '—')       as using_condition,
       coalesce(with_check, '—') as with_check_condition
  from pg_policies
 where schemaname = 'public'
   and tablename = 'students'
 order by policyname;